import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('./', import.meta.url);
const tokens = JSON.parse(await readFile(new URL('tokens.json', root), 'utf8'));
const prefix = tokens.meta.cssPrefix;
const flatten = (object, path = []) => Object.entries(object).flatMap(([key, value]) =>
  value && typeof value === 'object' && !Array.isArray(value)
    ? flatten(value, [...path, key])
    : [[`${prefix}-${[...path, key].join('-')}`, String(value)]]
);
const block = (selector, entries) => `${selector} {\n${entries.map(([key, value]) => `  --${key}: ${value};`).join('\n')}\n}`;
const shared = [...flatten(tokens.foundations), ...flatten(tokens.components)];
const light = flatten(tokens.themes.light);
const dark = flatten(tokens.themes.dark);
if (light.map(([key]) => key).join() !== dark.map(([key]) => key).join()) {
  throw new Error('Light and dark must define the same semantic token paths.');
}
if (new Set([...shared, ...light].map(([key]) => key)).size !== shared.length + light.length) {
  throw new Error('Duplicate CSS token names.');
}

// Check only specified solid foreground/background pairs; illustration colors
// and subtle decorative borders are intentionally not text colors.
const luminance = hex => {
  if (!/^#[0-9a-f]{6}$/i.test(hex)) throw new Error(`Expected opaque hex color: ${hex}`);
  const c = hex.slice(1).match(/../g).map(v => parseInt(v, 16) / 255)
    .map(v => v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
  return c[0] * 0.2126 + c[1] * 0.7152 + c[2] * 0.0722;
};
const contrast = (a, b) => {
  const values = [luminance(a), luminance(b)].sort((a, b) => b - a);
  return (values[0] + 0.05) / (values[1] + 0.05);
};
const report = [];
for (const [theme, { color: c }] of Object.entries(tokens.themes)) {
  const pairs = [];
  for (const bg of ['canvas', 'surface', 'subtle', 'hover', 'selected']) {
    for (const fg of ['primary', 'secondary']) pairs.push([`text.${fg}/bg.${bg}`, c.text[fg], c.bg[bg], 4.5]);
  }
  for (const state of ['default', 'hover', 'pressed']) pairs.push([`text.on-accent/accent.${state}`, c.text['on-accent'], c.accent[state], 4.5]);
  for (const [name, value] of Object.entries(c.status)) pairs.push([`status.${name}/surface`, value, c.bg.surface, 4.5]);
  for (const [name, value] of Object.entries(c.team)) pairs.push([`team.${name}/piece`, value, c.piece.surface, 3]);
  pairs.push(['focus/surface', c.focus, c.bg.surface, 3], ['border.control/surface', c.border.control, c.bg.surface, 3], ['piece.ink/piece.surface', c.piece.ink, c.piece.surface, 4.5]);
  for (const [name, fg, bg, minimum] of pairs) {
    const ratio = contrast(fg, bg);
    if (ratio < minimum) throw new Error(`${theme} ${name}: ${ratio.toFixed(2)} < ${minimum}`);
    report.push({ theme, pair: name, ratio: Number(ratio.toFixed(2)), minimum });
  }
}

const css = `/* Generated by build-tokens.mjs from tokens.json. Do not edit by hand.\n   Style tokens only: no page layout, DOM structure or game logic. */\n\n${block(':root', shared)}\n\n${block(':root, :root[data-theme="light"]', light)}\n\n:root { color-scheme: light; }\n\n${block(':root[data-theme="dark"]', dark)}\n\n:root[data-theme="dark"] { color-scheme: dark; }\n\n@media (prefers-reduced-motion: reduce) {\n  :root { --${prefix}-motion-fast: 0ms; --${prefix}-motion-normal: 0ms; }\n}\n`;
await writeFile(new URL('tokens.css', root), css);
await writeFile(new URL('contrast-report.json', root), JSON.stringify({ note: 'Solid-color token checks only. Validate actual rendered UI, textures, custom combinations and images separately.', pairs: report }, null, 2) + '\n');
console.log(`Generated tokens.css; ${report.length} color pairs passed.`);
